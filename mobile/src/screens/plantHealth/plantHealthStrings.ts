const BY_LANGUAGE: Record<string, Partial<Record<PlantStringKey, string>>> = { Hindi: HI, Telugu: TE };

const LOCALE_BY_LANGUAGE: Record<string, string> = { Hindi: "hi-IN", Telugu: "te-IN" };

export function plantString(language: string, key: PlantStringKey, params?: Record<string, string | number>) {
  let text: string = BY_LANGUAGE[language]?.[key] ?? EN[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function usePlantStrings() {
  const { language } = useLanguage();
  const s = useCallback(
    (key: PlantStringKey, params?: Record<string, string | number>) => plantString(language, key, params),
    [language]
  );
  const formatDate = useCallback(
    (iso: string | null | undefined) => {
      if (!iso) return "";
      const date = new Date(iso);
      if (Number.isNaN(date.getTime())) return "";
      try {
        return date.toLocaleDateString(LOCALE_BY_LANGUAGE[language] || "en-IN", { day: "numeric", month: "short" });
      } catch {
        return date.toDateString();
      }
    },
    [language]
  );
  return { s, language, formatDate };
}
